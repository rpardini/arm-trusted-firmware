void dpm_reset(struct mtk_mcu *mcu)
{
	struct dpm_regs *dpm = mcu->priv;

	/* write bootargs */
	mmio_write_32(&dpm->twam_window_len, 0x0);
	mmio_write_32(&dpm->twam_mon_type, 0x0);

	/* free RST */
	mmio_setbits_32(&dpm->sw_rstn, DPM_SW_RSTN_RESET);
}

int dpm_init(void)
{
	int i;
	struct mtk_mcu *dpm;

	NOTICE("MT8195 %s\n", __func__);

	if (dpm_4ch_init())
		return -1;

	/* config DPM SRAM layout */
	mmio_clrsetbits_32(&mtk_dpm->sw_rstn, DPM_MEM_RATIO_MASK,
			   DPM_MEM_RATIO_CFG1);

	for (i = 0; i < ARRAY_SIZE(dpm_mcu); i++) {
		dpm = &dpm_mcu[i];
		if (mtk_init_mcu(dpm))
			return -1;
	}

	if (dpm_4ch_para_setting())
		return -1;

	return 0;
}
